import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
await rm('dist', { recursive: true, force: true });
await mkdir('dist', { recursive: true });
const shared = { entryPoints: ['src/index.ts'], bundle: true, minify: true, target: ['es2022'], sourcemap: true, legalComments: 'linked' };
await build({ ...shared, format: 'esm', outfile: 'dist/siftbar.js' });
await build({ ...shared, format: 'iife', globalName: 'SiftbarLibrary', outfile: 'dist/siftbar.browser.js', footer: { js: 'globalThis.Siftbar = SiftbarLibrary.Siftbar;' } });
execFileSync('node_modules/.bin/tsc', ['--emitDeclarationOnly'], { stdio: 'inherit' });
const base = await readFile('src/styles/base.css', 'utf8');
const theme = await readFile('src/styles/theme.css', 'utf8');
await writeFile('dist/base.css', base);
await writeFile('dist/styles.css', `${base}\n${theme}`);
await cp('LICENSE', 'dist/LICENSE');
await cp('node_modules/@floating-ui/dom/LICENSE', 'dist/LICENSE-floating-ui-dom');
await cp('node_modules/@floating-ui/core/LICENSE', 'dist/LICENSE-floating-ui-core');
await cp('node_modules/@floating-ui/utils/LICENSE', 'dist/LICENSE-floating-ui-utils');
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
await writeFile('dist/version.json', JSON.stringify({ version: pkg.version, license: pkg.license }, null, 2));
console.log(`Built Siftbar ${pkg.version}: ESM, browser script, declarations, CSS, and license records.`);
